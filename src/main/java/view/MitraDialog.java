    /** Mengisi seluruh kolom dari objek data. */
    private void isiDariData() {
        txtNama.setText(m.getNamaMitra() == null ? "" : m.getNamaMitra());
        txtJenis.setText(m.getJenisMitra() == null ? "" : m.getJenisMitra());
        txtEmail.setText(m.getEmail() == null ? "" : m.getEmail());
        txtAlamat.setText(m.getAlamat() == null ? "" : m.getAlamat());
        cmbStatus.setSelectedItem(m.getStatusMitra() == null ? "aktif" : m.getStatusMitra());
    }

    /** @return null bila valid, atau pesan galat. */
    private String validasi() {
        if (txtNama.getText().trim().isEmpty()) { return "Nama Mitra wajib diisi."; }
        if (txtJenis.getText().trim().isEmpty()) { return "Jenis Mitra wajib diisi."; }
        if (txtEmail.getText().trim().isEmpty()) { return "Email wajib diisi."; }
        if (txtAlamat.getText().trim().isEmpty()) { return "Alamat wajib diisi."; }
        return null;
    }


    private void simpan() {
        String galat = validasi();
        if (galat != null) {
            tampilGalat(galat);
            return;
        }
        m.setNamaMitra(txtNama.getText().trim());
        m.setJenisMitra(txtJenis.getText().trim());
        m.setEmail(txtEmail.getText().trim());
        m.setAlamat(txtAlamat.getText().trim());
        m.setStatusMitra((String) cmbStatus.getSelectedItem());
        boolean ok = baru ? controller.tambah(m) : controller.ubah(m);
        if (!ok) {
            tampilGalat(controller.getPesan());
            return;
        }

        tersimpan = true;
        dispose();
    }

    private void tampilGalat(String pesan) {
        lblPesan.setText(pesan);
    }

