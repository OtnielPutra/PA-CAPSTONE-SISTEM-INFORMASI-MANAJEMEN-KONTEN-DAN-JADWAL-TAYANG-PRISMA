    /** Mengisi combo pilihan tetap (status/jenis/kategori/role). */
    private void isiComboStatis() {
        cmbStatus.removeAllItems();
        for (String item : Mitra.DAFTAR_STATUS) {
            cmbStatus.addItem(item);
        }
    }

