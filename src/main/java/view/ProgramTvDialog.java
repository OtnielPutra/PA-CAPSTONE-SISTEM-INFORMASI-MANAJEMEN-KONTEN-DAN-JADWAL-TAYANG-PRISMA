    /** Mengisi combo pilihan tetap (status/jenis/kategori/role). */
    private void isiComboStatis() {
        cmbKategori.removeAllItems();
        for (String item : ProgramTV.DAFTAR_KATEGORI) {
            cmbKategori.addItem(item);
        }
        cmbStatus.removeAllItems();
        for (String item : ProgramTV.DAFTAR_STATUS) {
            cmbStatus.addItem(item);
        }
    }

    private void isiCombo() {

    }

    /** Mengisi seluruh kolom dari objek data. */
    private void isiDariData() {
        txtNama.setText(p.getNamaProgram() == null ? "" : p.getNamaProgram());
        cmbKategori.setSelectedItem(p.getKategoriProgram());
        txtUrl.setText(p.getUrlProgram() == null ? "" : p.getUrlProgram());
        cmbStatus.setSelectedItem(p.getStatusProgram() == null ? "aktif" : p.getStatusProgram());
    }

    /** @return null bila valid, atau pesan galat. */
    private String validasi() {
        if (txtNama.getText().trim().isEmpty()) { return "Nama Program wajib diisi."; }
        return null;
    }


    private void simpan() {
        String galat = validasi();
        if (galat != null) {
            tampilGalat(galat);
            return;
        }
        p.setNamaProgram(txtNama.getText().trim());
        p.setKategoriProgram((String) cmbKategori.getSelectedItem());
        p.setUrlProgram(txtUrl.getText().trim());
        p.setStatusProgram((String) cmbStatus.getSelectedItem());
        boolean ok = baru ? controller.tambah(p) : controller.ubah(p);
        if (!ok) {
            tampilGalat(controller.getPesan());
            return;
        }

        tersimpan = true;
        dispose();
    }

    private void tampilGalat(String pesan) {
        lblPesan.setText(pesan);
    }

