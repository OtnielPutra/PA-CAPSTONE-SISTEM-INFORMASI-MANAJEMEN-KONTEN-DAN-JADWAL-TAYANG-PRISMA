    /** Konstruktor aplikasi: data == null berarti menambah data baru. */
    public ProgramTvDialog(java.awt.Window owner, ProgramTV data) {
        super(owner, java.awt.Dialog.ModalityType.APPLICATION_MODAL);
        this.baru = data == null;
        this.p = baru ? new ProgramTV() : data;
        initComponents();
        setTitle(baru ? "Tambah Program" : "Ubah Program");
        lblKepala.setText(baru ? "Tambah Program" : "Ubah Program");
        pasangSpinner();
        isiComboStatis();
        isiCombo();
        isiDariData();
    }

    /** Menampilkan dialog modal. @return true bila data berhasil disimpan. */
    public boolean tampilkan() {
        pack();
        setLocationRelativeTo(getOwner());
        setVisible(true);
        return tersimpan;
    }

    public boolean isTersimpan() {
        return tersimpan;
    }

