    /** Konstruktor aplikasi: data == null berarti menambah data baru. */
    public KanalDialog(java.awt.Window owner, Kanal data) {
        super(owner, java.awt.Dialog.ModalityType.APPLICATION_MODAL);
        this.baru = data == null;
        this.k = baru ? new Kanal() : data;
        initComponents();
        setTitle(baru ? "Tambah Kanal" : "Ubah Kanal");
        lblKepala.setText(baru ? "Tambah Kanal" : "Ubah Kanal");
        pasangSpinner();
        isiComboStatis();
        isiCombo();
        isiDariData();
    }

    /** Menampilkan dialog modal. @return true bila data berhasil disimpan. */
    public boolean tampilkan() {
        pack();
        setLocationRelativeTo(getOwner());
        setVisible(true);
        return tersimpan;
    }

    public boolean isTersimpan() {
        return tersimpan;
    }

