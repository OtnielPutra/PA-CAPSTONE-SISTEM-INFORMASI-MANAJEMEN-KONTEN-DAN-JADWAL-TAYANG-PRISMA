    /** Mengisi combo pilihan tetap (status/jenis/kategori/role). */
    private void isiComboStatis() {
        cmbJenis.removeAllItems();
        for (String item : Kanal.DAFTAR_JENIS) {
            cmbJenis.addItem(item);
        }
        cmbStatus.removeAllItems();
        for (String item : Kanal.DAFTAR_STATUS) {
            cmbStatus.addItem(item);
        }
    }

    private void isiCombo() {

    }

    /** Mengisi seluruh kolom dari objek data. */
    private void isiDariData() {
        txtNama.setText(k.getNamaKanal() == null ? "" : k.getNamaKanal());
        cmbJenis.setSelectedItem(k.getJenisKanal());
        txtPlatform.setText(k.getPlatform() == null ? "" : k.getPlatform());
        cmbStatus.setSelectedItem(k.getStatusKanal() == null ? "aktif" : k.getStatusKanal());
    }

    /** @return null bila valid, atau pesan galat. */
    private String validasi() {
        if (txtNama.getText().trim().isEmpty()) { return "Nama Kanal wajib diisi."; }
        if (txtPlatform.getText().trim().isEmpty()) { return "Platform wajib diisi."; }
        return null;
    }


    private void simpan() {
        String galat = validasi();
        if (galat != null) {
            tampilGalat(galat);
            return;
        }
        k.setNamaKanal(txtNama.getText().trim());
        k.setJenisKanal((String) cmbJenis.getSelectedItem());
        k.setPlatform(txtPlatform.getText().trim());
        k.setStatusKanal((String) cmbStatus.getSelectedItem());
        boolean ok = baru ? controller.tambah(k) : controller.ubah(k);
        if (!ok) {
            tampilGalat(controller.getPesan());
            return;
        }

        tersimpan = true;
        dispose();
    }

    private void tampilGalat(String pesan) {
        lblPesan.setText(pesan);
    }

